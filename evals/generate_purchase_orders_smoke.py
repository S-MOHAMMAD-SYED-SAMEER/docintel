"""Build the small `purchase_orders_smoke` fixture.

Run with `python -m evals.generate_purchase_orders_smoke`.

Three purchase orders, not twenty: this exists to prove the harness carries a
second document type end to end, not to benchmark purchase-order accuracy. No
quality claim is made from it.

As with the invoice dataset, each record is rendered into a PDF *and* written
to `labels.json`, so the labels describe what the document says rather than
what a model claims it says.
"""

import json
from decimal import Decimal
from pathlib import Path

from evals.generate_invoices_v1 import build_pdf

DATASET_NAME = "purchase_orders_smoke"
DATASET_DIR = Path(__file__).resolve().parent / "datasets" / DATASET_NAME

ORDERS = [
    {
        "vendor_name": "Acme Supplies BV",
        "customer_name": "Beta Ltd",
        "currency": "EUR",
        "order_date": "2026-02-03",
        "delivery_date": "2026-02-17",
        "tax_rate": "0.21",
        "rows": [("Widget, blue", "10", "40.00"), ("Widget, red", "5", "40.00")],
    },
    {
        "vendor_name": "Northwind Trading Ltd",
        "customer_name": "Corvus Studio",
        "currency": "GBP",
        "order_date": "2026-03-11",
        "delivery_date": "2026-03-25",
        "tax_rate": "0.20",
        "rows": [("Hex bolt M8 (box of 100)", "8", "12.50")],
    },
    {
        "vendor_name": "Bluegrass Hardware Inc",
        "customer_name": "Tallow Works",
        "currency": "USD",
        "order_date": "2026-04-06",
        "delivery_date": "2026-04-20",
        "tax_rate": "0.0825",
        "rows": [
            ("Packing crate, large", "12", "27.25"),
            ("Courier delivery", "2", "18.00"),
            ("Laminated sign, A2", "3", "65.00"),
        ],
    },
]


def _money(value: Decimal) -> str:
    return f"{value.quantize(Decimal('0.01'))}"


def build_orders() -> list[dict[str, object]]:
    orders: list[dict[str, object]] = []

    for index, spec in enumerate(ORDERS, start=1):
        rows = [
            {
                "description": description,
                "quantity": quantity,
                "unit_price": unit_price,
                "amount": _money(Decimal(quantity) * Decimal(unit_price)),
            }
            for description, quantity, unit_price in spec["rows"]
        ]
        subtotal = sum((Decimal(row["amount"]) for row in rows), Decimal(0))
        tax = (subtotal * Decimal(spec["tax_rate"])).quantize(Decimal("0.01"))

        orders.append(
            {
                "document_id": f"po-{index:03d}",
                "filename": f"po-{index:03d}.pdf",
                "fields": {
                    "purchase_order_number": f"PO-2026-{2000 + index}",
                    "order_date": spec["order_date"],
                    "delivery_date": spec["delivery_date"],
                    "vendor_name": spec["vendor_name"],
                    "customer_name": spec["customer_name"],
                    "currency": spec["currency"],
                    "subtotal": _money(subtotal),
                    "tax": _money(tax),
                    "total": _money(subtotal + tax),
                    "line_items": rows,
                },
            }
        )

    return orders


def render_pages(order: dict[str, object]) -> list[str]:
    fields = order["fields"]

    header = [
        f"{fields['customer_name']}",
        "",
        f"PURCHASE ORDER {fields['purchase_order_number']}",
        f"Order date {fields['order_date']}",
        f"Requested delivery {fields['delivery_date']}",
        "",
        f"Supplier: {fields['vendor_name']}",
    ]

    table = ["Description                     Qty   Unit price     Amount"]
    for row in fields["line_items"]:
        table.append(
            f"{row['description']:<30}  {row['quantity']:>3}   "
            f"{row['unit_price']:>10}   {row['amount']:>10}"
        )
    table += [
        "",
        f"Subtotal   {fields['currency']} {fields['subtotal']}",
        f"Tax        {fields['currency']} {fields['tax']}",
        f"ORDER TOTAL {fields['currency']} {fields['total']}",
    ]

    return ["\n".join(header), "\n".join(table)]


def main() -> None:
    DATASET_DIR.mkdir(parents=True, exist_ok=True)
    orders = build_orders()

    for order in orders:
        (DATASET_DIR / str(order["filename"])).write_bytes(
            build_pdf(render_pages(order))
        )

    labels = {
        "dataset": DATASET_NAME,
        "doc_type": "purchase_order",
        "synthetic": True,
        "description": (
            "Three synthetic purchase orders generated by "
            "evals/generate_purchase_orders_smoke.py. This is a smoke fixture "
            "that proves the harness carries a second document type, not a "
            "benchmark: no accuracy claim should be made from three documents."
        ),
        "documents": orders,
    }
    (DATASET_DIR / "labels.json").write_text(
        json.dumps(labels, indent=2, ensure_ascii=False) + "\n"
    )
    print(f"Wrote {len(orders)} documents and labels.json to {DATASET_DIR}")


if __name__ == "__main__":
    main()
